"""Bake the 1,133-star sample and the spectrum ribbon's bands into site/listen/stars.js.

The page can't read CSV or YAML at runtime (no build step on the site, strict
CSP), so this writes one plain script that assigns window.LISTEN_STARS:

  stars         [name, ra_deg, dec_deg, bands, first_mjd] in sample-CSV order.
                That order is load-bearing: the snapshot's progress.searched
                bitmap sets bit i for star i of this same list.
  bands         rung 4's human-transmitter bands, read from ladder.yaml (Plan A
                Task 4). Until ladder.yaml exists, Plan A Task 4's published
                initial list is used and bands_source says so.
  notches       receiver notch filters that record no data (spec §5).
  receivers     the L- and S-band ranges recorded (Price et al. 2020).

    python scripts/bake_stars.py [--csv data/gbt_sample_price2020.csv] [--ladder ladder.yaml]
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CSV = ROOT / "data" / "gbt_sample_price2020.csv"
FIXTURE_CSV = ROOT / "tests" / "fixtures" / "gbt_sample_price2020.csv"  # until Plan A lands data/
DEFAULT_LADDER = ROOT / "ladder.yaml"
OUT = ROOT / "site" / "listen" / "stars.js"

# Plan A Task 4's initial ladder.yaml rung4 list, used only until ladder.yaml exists.
FALLBACK_BANDS = [
    ("gps_l5", 1166.45, 1186.45), ("gps_l2", 1217.60, 1237.60), ("inmarsat", 1525.0, 1559.0),
    ("gps_l1", 1565.42, 1585.42), ("glonass", 1598.0, 1606.0), ("iridium", 1616.0, 1626.5),
    ("spacecraft_telemetry", 2200.0, 2290.0), ("wifi_ism", 2400.0, 2483.5),
]
NOTCHES = [[1200.0, 1341.0], [2300.0, 2360.0]]           # spec §5: the receiver notches hold no data
RECEIVERS = {"L": [1100.0, 1900.0], "S": [1800.0, 2800.0]}  # Price et al. 2020, recorded bandwidths


def read_stars(csv_path: Path) -> list[list]:
    with open(csv_path, encoding="utf-8") as fh:
        rows = csv.DictReader(line for line in fh if not line.startswith("#"))
        return [[r["star"], round(float(r["ra_deg"]), 5), round(float(r["dec_deg"]), 5), r["bands"],
                 round(float(r["first_mjd"]), 4)] for r in rows]


def read_bands(ladder_path: Path) -> tuple[list[list], str]:
    if ladder_path.is_file():
        cfg = yaml.safe_load(ladder_path.read_text(encoding="utf-8")) or {}
        bands = (cfg.get("rung4") or {}).get("bands_mhz") or {}
        return [[name, float(lo), float(hi)] for name, (lo, hi) in bands.items()], "ladder.yaml"
    return [list(b) for b in FALLBACK_BANDS], "plan-a-task4-initial (ladder.yaml not frozen yet)"


def bake(csv_path: Path, ladder_path: Path) -> str:
    stars = read_stars(Path(csv_path))
    bands, source = read_bands(Path(ladder_path))
    data = {"count": len(stars), "sample": "Price et al. 2020 (arXiv:1906.07750), Tables 1-2",
            "stars": stars, "bands": bands, "bands_source": source, "notches": NOTCHES,
            "receivers": RECEIVERS}
    body = json.dumps(data, separators=(",", ":"), ensure_ascii=False)
    return ("/* Generated by seti-hunter scripts/bake_stars.py from the sample CSV and ladder.yaml.\n"
            "   Do not hand-edit: re-run the script. */\n"
            f"window.LISTEN_STARS = {body};\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Bake site/listen/stars.js")
    ap.add_argument("--csv", default=str(DEFAULT_CSV if DEFAULT_CSV.is_file() else FIXTURE_CSV))
    ap.add_argument("--ladder", default=str(DEFAULT_LADDER))
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args(argv)
    js = bake(Path(a.csv), Path(a.ladder))
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(js, encoding="utf-8", newline="\n")
    print(f"wrote {a.out} ({len(js)} bytes) from {a.csv}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
